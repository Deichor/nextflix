export type Locale = 'en' | 'tr';
export type Vars = Record<string, string | number>;
export type TFunction = (key: MessageKey, vars?: Vars) => string;

const DICTS: Record<Locale, Messages> = { en, tr };
const INTL: Record<Locale, string> = { en: 'en-US', tr: 'tr-TR' };

export const intlLocale = (locale: Locale) => INTL[locale];
export const isLocale = (v: unknown): v is Locale => v === 'en' || v === 'tr';

export function translate(locale: Locale, key: MessageKey, vars?: Vars): string {
  const msg = DICTS[locale][key] ?? en[key];
  let text: string;
  if (typeof msg === 'string') text = msg;
  else text = locale === 'en' && Number(vars?.count) === 1 ? msg.one : msg.other;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (vars[name] === undefined ? m : String(vars[name])));
}

function toDate(d: string): Date {
  return new Date(/^\d{4}-\d{2}-\d{2}$/.test(d) ? `${d}T00:00:00` : d);
}

export function formatDate(locale: Locale, date: string): string {
  const d = toDate(date);
  if (Number.isNaN(d.getTime())) return '';
  try {
    return d.toLocaleDateString(INTL[locale], { year: 'numeric', month: 'long', day: 'numeric' });
  } catch {
    return date;
  }
}

/** Runtime in minutes as "1h 36m" / "1 sa 36 dk". */
export function formatDuration(locale: Locale, minutes: number): string {
  const total = Math.max(0, Math.round(minutes));
  const h = Math.floor(total / 60);
  const m = total % 60;
  if (h > 0 && m > 0) return translate(locale, 'format.durationHM', { h, m });
  if (h > 0) return translate(locale, 'format.durationH', { h });
  return translate(locale, 'format.durationM', { m });
}

export interface I18n {
  locale: Locale;
  t: TFunction;
  date: (d: string) => string;
  duration: (minutes: number) => string;
}

export function makeI18n(locale: Locale): I18n {
  return {
    locale,
    t: (key, vars) => translate(locale, key, vars),
    date: d => formatDate(locale, d),
    duration: m => formatDuration(locale, m),
  };
}

export const I18nContext = createContext<I18n>(makeI18n('en'));
export const useI18n = () => useContext(I18nContext);
export const useT = () => useContext(I18nContext).t;
