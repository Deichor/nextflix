# Downloads Inter (SIL OFL 1.1), writes Latin subsets of three weights to core/src/main/res/font and the
# banner wordmark (NEXTFLIX in Inter ExtraBold) as vector path data to app/src/main/res/drawable/banner.xml.
# Run by tools/fonts.sh in a python container.
import io
import sys
import urllib.request
import zipfile

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont

URL = "https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip"
ROOT = sys.argv[1]
WEIGHTS = {"Regular": "inter_regular", "SemiBold": "inter_semibold", "ExtraBold": "inter_extrabold"}
UNICODES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) + list(range(0x2010, 0x203B)) + [0x20AC, 0x2122, 0x2212]

data = urllib.request.urlopen(URL, timeout=120).read()
zf = zipfile.ZipFile(io.BytesIO(data))
names = zf.namelist()


def ttf(weight):
    name = next(n for n in names if n.endswith(f"/Inter-{weight}.ttf") or n == f"Inter-{weight}.ttf")
    return TTFont(io.BytesIO(zf.read(name)))


for weight, res in WEIGHTS.items():
    font = ttf(weight)
    opts = Options()
    opts.hinting = False
    opts.desubroutinize = True
    opts.name_IDs = ["*"]
    sub = Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    font.save(f"{ROOT}/core/src/main/res/font/{res}.ttf")

lic = next(n for n in names if n.upper().endswith("LICENSE.TXT"))
with open(f"{ROOT}/core/INTER-LICENSE.txt", "wb") as f:
    f.write(zf.read(lic))

# Banner: 320x180, the brand wordmark (red, 800 weight, 0.08em letter spacing) centered
font = ttf("ExtraBold")
upm = font["head"].unitsPerEm
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
text = "NEXTFLIX"
size = 46.0
scale = size / upm
spacing = 0.08 * upm
advances = [font["hmtx"][cmap[ord(c)]][0] for c in text]
width = (sum(advances) + spacing * (len(text) - 1)) * scale
cap = font["OS/2"].sCapHeight * scale
x0 = (320 - width) / 2
baseline = 90 + cap / 2
pen = SVGPathPen(glyphs, ntos=lambda v: ("%.2f" % v).rstrip("0").rstrip("."))
x = 0.0
for c, adv in zip(text, advances):
    glyphs[cmap[ord(c)]].draw(TransformPen(pen, (scale, 0, 0, -scale, x0 + x * scale, baseline)))
    x += adv + spacing
path = pen.getCommands()

banner = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/fonts.sh: the NEXTFLIX wordmark in Inter ExtraBold -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="320dp"
    android:height="180dp"
    android:viewportWidth="320"
    android:viewportHeight="180">
    <path android:fillColor="#141414" android:pathData="M0,0h320v180h-320z" />
    <path android:fillColor="#E50914" android:pathData="{path}" />
</vector>
"""
with open(f"{ROOT}/app/src/main/res/drawable/banner.xml", "w") as f:
    f.write(banner)
print("fonts and banner written")
