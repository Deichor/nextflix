// Converts the lucide icons listed below to Compose ImageVector path data (core/.../ui/icons/Lucide.kt).
// Run by tools/lucide.sh with the webOS app's node_modules (lucide-react) mounted at /nm.
import { readFileSync, writeFileSync } from 'node:fs';

const ICONS = [
  'house', 'search', 'tv', 'film', 'settings', 'shuffle', 'play', 'pause', 'info', 'plus', 'minus', 'check', 'x',
  'chevron-left', 'chevron-right', 'chevron-up', 'chevron-down', 'chevrons-right', 'arrow-left', 'arrow-big-up',
  'delete', 'mic', 'rotate-ccw', 'rotate-cw', 'skip-forward', 'thumbs-up', 'thumbs-down', 'heart', 'circle-alert',
  'calendar-clock', 'clapperboard', 'message-square', 'type', 'zap', 'captions', 'languages', 'volume-2', 'server',
  'pencil', 'trash-2', 'loader-circle', 'clock', 'list-plus',
  // profile avatars (same keys as the web app)
  'smile', 'star', 'rocket', 'ghost', 'cat', 'dog', 'bird', 'flame', 'crown', 'gamepad-2', 'sun', 'moon', 'leaf',
  'snowflake', 'popcorn', 'pizza', 'bot', 'skull',
];

const n = v => Number(v);
const fmt = v => String(Math.round(v * 1000) / 1000);

function toPath([tag, a]) {
  switch (tag) {
    case 'path': return a.d;
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline':
    case 'polygon': {
      const p = a.points.trim().split(/[\s,]+/);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      return tag === 'polygon' ? `${d}Z` : d;
    }
    case 'circle':
    case 'ellipse': {
      const cx = n(a.cx), cy = n(a.cy), rx = n(a.rx ?? a.r), ry = n(a.ry ?? a.r);
      return `M${fmt(cx - rx)} ${fmt(cy)}a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(2 * rx)} 0a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(-2 * rx)} 0Z`;
    }
    case 'rect': {
      const x = n(a.x || 0), y = n(a.y || 0), w = n(a.width), h = n(a.height);
      const rx = Math.min(n(a.rx ?? a.ry ?? 0), w / 2), ry = Math.min(n(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx) return `M${fmt(x)} ${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`;
      return `M${fmt(x + rx)} ${fmt(y)}h${fmt(w - 2 * rx)}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(rx)} ${fmt(ry)}v${fmt(h - 2 * ry)}` +
        `a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(-rx)} ${fmt(ry)}h${fmt(-(w - 2 * rx))}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(-rx)} ${fmt(-ry)}` +
        `v${fmt(-(h - 2 * ry))}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(rx)} ${fmt(-ry)}Z`;
    }
  }
  throw new Error(`unsupported element ${tag}`);
}

const pascal = s => s.split('-').map(p => p[0].toUpperCase() + p.slice(1)).join('');
const version = JSON.parse(readFileSync('/nm/lucide-react/package.json', 'utf8')).version;
const out = [];
// Aliases re-export another icon file
function iconSource(name) {
  const src = readFileSync(`/nm/lucide-react/dist/esm/icons/${name}.mjs`, 'utf8');
  const alias = src.indexOf('node: [') < 0 && src.match(/from '\.\/([\w-]+)\.mjs'/);
  return alias ? iconSource(alias[1]) : src;
}

for (const name of ICONS) {
  const src = iconSource(name);
  const start = src.indexOf('node: [');
  if (start < 0) throw new Error(`no icon data in ${name}`);
  let depth = 0;
  let end = start + 6;
  for (; end < src.length; end++) {
    if (src[end] === '[') depth++;
    else if (src[end] === ']' && --depth === 0) break;
  }
  const node = Function(`return ${src.slice(start + 6, end + 1)}`)();
  const paths = node.map(toPath).map(d => `            "${d}",`).join('\n');
  out.push(`    val ${pascal(name)}: ImageVector by lazy {\n        lucide(\n            "${name}",\n${paths}\n        )\n    }`);
}

writeFileSync('/out/Lucide.kt', `// Generated by tools/lucide.sh from lucide-react ${version} (ISC license). Do not edit by hand.
package com.nextflix.tv.core.ui.icons

import androidx.compose.ui.graphics.vector.ImageVector

/** Lucide line icons (24x24, stroke 2) as ImageVectors; tint them with Icon(tint = ...). */
object Lucide {
${out.join('\n\n')}
}
`);
console.log(`${ICONS.length} icons written`);
